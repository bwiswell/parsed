"""A command's reference page, in Markdown: what it declares, how it's said, then seared's fields.

:func:`render_command` writes a :class:`~parsed.doc.introspect.CommandDoc` as ``zeared.doc`` writes a message: a
header with its constants, then what only a command says, then seared's own sections (its fields, enums and
variants), so the layers stay in step:

- **the header:** its name, a line of what it declares (its effect, whether it asks first, whether it's for a person
  at a terminal, the chain it's a step of), and its docstring;
- **Phrases:** each phrase, with its key template for policy;
- **Usage:** each phrase as a line says it, a ``<slot>`` for each slot, then its flags;
- **Arguments:** each slot and flag, the field it fills, and what its words are (its kind's
  :meth:`~parsed.kinds.Kind.describe`), a flag's short form beside it;
- **Examples:** its ``EXAMPLES``;
- **links** to its ``REPLY``, its ``INSTEAD`` and the classes it takes fields from.
"""

from __future__ import annotations

from collections.abc import Callable
from typing import TYPE_CHECKING

from seared.doc import render_enums, render_fields_table, render_header, render_variants

from parsed._walk._hints import label
from parsed.tree import Tree

from .introspect import CommandDoc, introspect_command

if TYPE_CHECKING:
    from parsed.command import Command

#: A page's link to another class's page.
type LinkFor = Callable[[type], str]

#: The line that ends every page.
GENERATED = '_Generated by `parsed.doc`, do not edit by hand._'


def _default_link(cls: type) -> str:
    return f'{cls.__name__}.md'


def render_command(cls: type[Command], link_for: LinkFor = _default_link) -> str:
    """The Markdown reference page for a command class."""
    found = introspect_command(cls)
    sections = [
        _header(found, link_for),
        _phrases(found),
        _usage(cls, found),
        _arguments(found),
        _examples(found),
        _links(found, link_for),
        render_fields_table(found.schema, link_for),
        render_enums(found.schema),
        render_variants(found.schema, link_for),
        GENERATED,
    ]
    return '\n\n'.join(section for section in sections if section) + '\n'


def _header(found: CommandDoc, link_for: LinkFor) -> str:
    said = []
    if found.effect is not None:
        said.append(f'`{found.effect.value}`')
    if found.asks:
        said.append('asks first')
    if found.interactive:
        said.append('for a person at a terminal')
    if found.chain is not None:
        said.append(f'a step of [`{found.chain.__name__}`]({link_for(found.chain)})')
    header = render_header(found.schema)
    if not said:
        return header
    title, _, rest = header.partition('\n')
    return '\n\n'.join(part for part in (title, ' · '.join(said), rest.strip()) if part)


def _phrases(found: CommandDoc) -> str:
    rows = [
        f'| `{phrase}`{" (extra)" if at else ""} | `{key}` |'
        for at, (phrase, key) in enumerate(zip((found.phrase, *found.extra_phrases), found.keys, strict=True))
    ]
    return '\n'.join(['## Phrases', '', '| phrase | key |', '|--------|-----|', *rows])


def _usage(cls: type[Command], found: CommandDoc) -> str:
    tree = Tree([cls])
    lines = [tree.usage_of(cls, at) for at in range(1 + len(found.extra_phrases))]
    return '\n'.join(['## Usage', '', '```', *lines, '```'])


def _arguments(found: CommandDoc) -> str:
    fields = {spec.attr: spec.field for spec in found.schema.cls.__seared_fields__}
    rows = []
    for slot in found.slots:
        said = f'<{slot.name} …>' if slot.rest else f'<{slot.name}> …' if slot.many else f'<{slot.name}>'
        rows.append(f'| `{said}` | `{slot.field}` | {_cell(slot.kind.describe(fields[slot.field]))} |')
    for flag in found.flags:
        said = f'--{flag.name}' if flag.switch else f'--{flag.name} <{label(flag.kind, fields[flag.field], flag.name)}>'
        said = f'`-{flag.short}`, `{said}`' if flag.short else f'`{said}`'
        what = ('off when given' if flag.negated else 'on when given') if flag.switch else None
        what = what or flag.kind.describe(fields[flag.field])
        rows.append(f'| {said} | `{flag.field}` | {_cell(what)} |')
    if not rows:
        return ''
    return '\n'.join(['## Arguments', '', '| said | field | its words |', '|------|-------|-----------|', *rows])


def _examples(found: CommandDoc) -> str:
    if not found.examples:
        return ''
    return '\n'.join(['## Examples', '', '```', *found.examples, '```'])


def _links(found: CommandDoc, link_for: LinkFor) -> str:
    said = []
    if found.reply is not None:
        said.append(f'Reply [`{found.reply.__name__}`]({link_for(found.reply)})')
    if found.instead is not None:
        said.append(f'Instead [`{found.instead.__name__}`]({link_for(found.instead)})')
    said += [f'Fields from [`{cls.__name__}`]({link_for(cls)})' for cls in found.fields_from]
    return ' · '.join(said)


def _cell(text: str) -> str:
    """Text for a table's cell: a pipe escaped."""
    return text.replace('|', '\\|')
